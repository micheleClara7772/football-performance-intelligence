"""Video-first FPI walkthrough that needs NO match file, account or paid API.

Source is an already validated, short CC BY 4.0 SoccerTrack sample.
The bundled clip is automatically generated by a private GitHub workflow.
This is a REAL ByteTrack proof, not FIFA footage or full-match tracking.
"""
from __future__ import annotations

import json
from pathlib import Path

import streamlit as st

_ROOT = Path(__file__).resolve().parents[3]
_VIDEO = _ROOT / "assets" / "fpi-video" / "real-bytetrack-12s.mp4"
_REPORT = _ROOT / "assets" / "fpi-video" / "real-bytetrack-report.json"
_POSTER = _ROOT / "assets" / "fpi-video" / "real-bytetrack-poster.jpg"
_PUBLIC_FALLBACK = (
    "https://raw.githubusercontent.com/AtomScott/SoccerTrack-v2/"
    "main/docs/assets/demo-tracking.mp4"
)


def read_verified_demo_report(path: Path = _REPORT) -> dict | None:
    """Fail closed; never invent tracking measurements or read arbitrary paths."""
    if not path.is_file() or path.stat().st_size > 50_000:
        return None
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
        quality = data["mot_identity_benchmark"]
        if (
            data["source_match_id"] != "117093"
            or data["clip_seconds"] != 12.0
            or data["processed_frames"] != 60
            or quality["frames_evaluated"] != 60
            or not 0 <= quality["idf1"] <= 1
            or data["full_match_90min_tracking_validated"] is not False
            or data["ball_tracking_accuracy_validated"] is not False
        ):
            return None
        return data
    except (ValueError, TypeError, KeyError, OSError, json.JSONDecodeError):
        return None


def video_is_ready(video_path: Path = _VIDEO, report_path: Path = _REPORT) -> bool:
    return (
        video_path.is_file()
        and 100_000 <= video_path.stat().st_size <= 9_000_000
        and read_verified_demo_report(report_path) is not None
    )


